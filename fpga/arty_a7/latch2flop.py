#!/usr/bin/env python3
"""Copies src/debug_regs.v and src/lisa_dbg.v into gen/ with every
sky130_fd_sc_hd__dlrtp_1 latch replaced by an fpga_dlrtp flop (fpga_cells.v)
clocked by the module's clk.  The instantiation is

    sky130_fd_sc_hd__dlrtp_1   name
    (
       ... .RESET_B ( ), .GATE ( ), .D ( ), .Q ( )
    );

and becomes  fpga_dlrtp name ( .CLK(clk), ...  - the rest of the port list
is the same.  Usage: latch2flop.py <src dir> <out dir>"""
import pathlib
import re
import sys

src = pathlib.Path(sys.argv[1])
out = pathlib.Path(sys.argv[2])
out.mkdir(parents=True, exist_ok=True)
for name in ("debug_regs.v", "lisa_dbg.v"):
    text = (src / name).read_text()
    text, n = re.subn(r"sky130_fd_sc_hd__dlrtp_1(\s+\w+\s*\()",
                      r"fpga_dlrtp\1 .CLK(clk),", text)
    if n == 0:
        sys.exit(f"{name}: no latch instantiation found")
    (out / name).write_text(
        f"// Generated by fpga/arty_a7/latch2flop.py from src/{name}: "
        "the sky130 latches as flops.  Do not edit.\n" + text)
    print(f"{name}: {n} latch instantiations -> fpga_dlrtp")
